"""tab:ablation_robustness_condensed -- per-window hyperparameter robustness summary.

Source: reports/runs/run_ablation_results.txt (committed 108-run campaign, job 774769); aggregation in
sources.ablation_agg (default / best RECORDED, Delta_best + max-spread DERIVED). For FC, Delta_best is the
increase in macro-F1; for FL, the reduction in MAE (positive = improvement in both). All committed.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import sources as S

TASK_AC = {"fc": "\\ac{fc}", "fl": "\\ac{fl}"}
MODEL_AC = {"gb": "\\ac{gb}", "mlp": "\\ac{mlp}"}
# paper row order: FC {gb,mlp}x{20,50}, then FL {gb,mlp}x{20,50}
ORDER = [("fc", "gb"), ("fc", "mlp"), ("fl", "gb"), ("fl", "mlp")]


def build():
    ab = S.parse_bracket(S.RUNS / "run_ablation_results.txt")
    body = []
    for i, (task, model) in enumerate(ORDER):
        if i == 2:
            body.append("\\midrule")
        for w in ("20", "50"):
            a = S.ablation_agg(ab, task, model, [w])
            body.append("%s & %s & %s\\,ms & %s & %s & %s & %s \\\\" % (
                TASK_AC[task], MODEL_AC[model], w,
                S.fnum(a["default"], 3), S.fnum(a["best"], 3),
                "+%s (%s)" % (S.fnum(a["dbest"], 3), a["dbest_knob"]),
                "%s (%s)" % (S.fnum(a["spread"], 3), a["spread_knob"])))

    latex = r"""\begin{table}[ht]
\centering
\footnotesize
\caption{Condensed hyperparameter robustness summary across single-parameter ablations. For \ac{fc}, $\Delta_{\text{best}}$ denotes the increase in macro-\ac{f1}; for \ac{fl}, it denotes the reduction in \ac{mae}. Positive values therefore indicate improvement in both tasks. The maximum spread reports the largest best--worst difference within any single-parameter ablation group. The default cells are independent results from the ablation harness and can differ slightly from the Table~\ref{tab:reference_20ms} reference; for example, \ac{fl} \ac{mlp} at 20\,ms is $9.998$ here versus $10.20$ in the reference evaluation. Comparisons within each ablation group therefore use the corresponding default generated by the same harness. This difference is not a repeated-seed uncertainty estimate.}
\label{tab:ablation_robustness_condensed}
\begin{tabular}{@{}llcccll@{}}
\toprule
\textbf{Task} & \textbf{Model} & \textbf{Window} & \textbf{Default} & \textbf{Best metric} & \textbf{$\Delta_{\text{best}}$} & \textbf{Max. spread} \\
\midrule
%s
\bottomrule
\end{tabular}
\end{table}""" % "\n".join(body)

    S.write_table("ablation_robustness_condensed", latex, "run_ablation_results.txt (committed)")


if __name__ == "__main__":
    build()
